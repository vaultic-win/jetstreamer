pub fn verify_seal(pkg: &Path, sha: &str) -> Result<Value> {
    let path = pkg.join("deployment-seal-receipt.json");
    let seal = pinned(&path, sha)?;
    ensure!(
        seal["destination"] == json!(pkg)
            && seal["schema"] == "jetstreamer-sealed-deployment-receipt-v1"
            && seal["sealer_sha256"]
                == "e0d565f4450b25b527ffd4455a52e1861568548b826e86a6894a1ae127e811f3"
            && seal["remote_mutations"] == false,
        "incorrect deployment seal"
    );
    // SHA256SUMS is generated by the normal sealer, so all actually executed members are verified.
    for m in seal["members"].as_array().context("seal members")? {
        let name = text(&m["name"])?;
        ensure!(
            !name.is_empty() && !name.contains('/') && name != "." && name != "..",
            "invalid member"
        );
        ensure!(
            super::platform::sha(&read(&pkg.join(name))?) == m["sha256"],
            "different deployment member {name}"
        );
    }
    bound(&path)
}
pub fn envelope(row: &Value) -> Result<()> {
    ensure!(
        row["Id"] == UNIT
            && row["ActiveState"] == "active"
            && row["SubState"] == "running"
            && row["Job"] == ""
            && row["NRestarts"] == "0"
            && row["ControlGroup"] == CG
            && row["CPUQuotaPerSecUSec"] == "4s"
            && row["TasksMax"] == "512"
            && row["MemorySwapMax"] == "0"
            && row["MemoryHigh"] == "21474836480"
            && row["MemoryMax"] == "25769803776"
            && row["FreezerState"] == "running",
        "audit limits or native state differ"
    );
    let s = show(
        "horizonaudit.slice",
        "ActiveState,CPUQuotaPerSecUSec,MemoryHigh,MemoryMax,MemorySwapMax,TasksMax,ControlGroup",
    )?;
    ensure!(
        s["ActiveState"] == "active"
            && s["ControlGroup"] == "/horizonaudit.slice"
            && [
                "CPUQuotaPerSecUSec",
                "MemoryHigh",
                "MemoryMax",
                "MemorySwapMax",
                "TasksMax"
            ]
            .iter()
            .all(|k| s[k] == row[k]),
        "shared limits differ"
    );
    Ok(())
}
pub fn identity(row: &Value, pkg: &Path) -> Result<i32> {
    envelope(row)?;
    let pid: i32 = text(&row["MainPID"])?.parse()?;
    ensure!(pid > 1, "invalid pid");
    let exe = pkg.join("audit");
    let config = pkg.join("config.json");
    let argv = [string_path(&exe)?, "run-public", string_path(&config)?, ""].join("\0");
    ensure!(
        proc_exe(pid)? == exe
            && fs::read(proc_path(pid, "cmdline"))? == argv.as_bytes()
            && fs::read_to_string(proc_path(pid, "cgroup"))?.trim() == format!("0::{CG}"),
        "incorrect process identity"
    );
    Ok(pid)
}
