pub fn latest_fleet(require_idle: bool) -> Result<(Value, Value, Value)> {
    let mut p = base("root031959-live166167170-20261121-v1/ROOT_COMPLETE_OPERATIONAL_FLEET.json");
    let mut r = bound(&p)?;
    ensure!(
        r["sha256"] == "3d8c9286014771f888af14eb3a1ebfbe9a6b50dc27ae32f838c69973988069e3",
        "wrong starting fleet"
    );
    for _ in 0..64 {
        let out = output(
            "/usr/bin/python3",
            &[
                "-B",
                string_path(&observer().join("describe.py"))?,
                string_path(&p)?,
                text(&r["sha256"])?,
            ],
        )?;
        let cfg: Value = serde_json::from_str(&out)?;
        let successor = Path::new(text(&cfg["out"])?).join("ROOT_COMPLETE_OPERATIONAL_FLEET.json");
        if !successor.try_exists()? {
            if require_idle {
                let until = output("/usr/bin/date", &["-u", "-d", text(&cfg["due"])?, "+%s"])?
                    .parse::<u64>()?;
                ensure!(
                    until > now() + 180
                        && show(text(&cfg["timer"])?, "ActiveState")?["ActiveState"] == "active"
                        && !Path::new(text(&cfg["sample"])?).try_exists()?,
                    "cadence cycle currently in progress or imminent"
                );
            }
            return Ok((r.clone(), from_ref(&r)?, cfg));
        }
        let next = bound(&successor)?;
        let f = from_ref(&next)?;
        ensure!(
            f["previous_Root_operational_review"] == r,
            "broken cadence chain"
        );
        p = successor;
        r = next;
    }
    anyhow::bail!("too many cadence successors")
}
pub fn owners(f: &Value) -> Result<Value> {
    let mut out = vec![];
    for key in [
        "actual_executing_replays",
        "actual_active_private_diagnostics",
    ] {
        for entry in f[key].as_array().context("fleet rows")? {
            let prev = &entry["unit"];
            let n = show(
                text(&prev["Id"])?,
                "Id,MainPID,InvocationID,NRestarts,ActiveState",
            )?;
            ensure!(
                n["ActiveState"] == "active"
                    && n["NRestarts"] == "0"
                    && ["Id", "MainPID", "InvocationID"]
                        .iter()
                        .all(|k| n[k] == prev[k]),
                "producer {} changed",
                prev["Id"]
            );
            out.push(n);
        }
    }
    ensure!(out.len() == 6, "six-owner generation required");
    Ok(json!(out))
}
