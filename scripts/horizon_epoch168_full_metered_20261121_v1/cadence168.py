"""Register normal 168 in the existing chronological observer and status publisher."""
from copy import deepcopy

import status168
from evidence import bound, checked, durable, ensure_dir, need, utc

FIELD = 'current_metered168_observation'
STAGES = ('intent', 'gated', 'protected-bootstrap', 'protected-worker')
FIRST, LAST = 168 * 432000, 169 * 432000 - 1


def previous(fleet):
    reference = fleet.get(FIELD)
    rows = [r for k in ('actual_executing_replays', 'actual_active_bootstraps')
            for r in fleet[k] if r['epoch'] == 168]
    if reference is None:
        need(not rows, 'unregistered normal 168 row')
        return None
    record = checked(reference)
    owner = record['state']
    need(record['fleet'] == fleet['previous_Root_operational_review'] and record['sample'] == fleet['observer']
         and owner['prior_trace_terminal'] == fleet['terminal168_trace_mismatch']
         and len(rows) == int(owner['ordinary_canonical']), 'wrong normal 168 sample lineage')
    if rows:
        row, = rows
        need(row['epoch'] == 168 and row['admission'] == owner['admission'] and row['capture'] == reference
             and row['unit']['Id'] == status168.U and row['unit']['InvocationID'] == owner['actor']['producer_invocation_id']
             and int(row['unit']['MainPID']) == owner['actor']['producer_pid'] and row['start_ticks'] == owner['actor']['start_ticks']
             and row['observer_config'] == owner['observer_row'] and row['first_worker'] == owner['first_worker']
             and row['guard_protection'] == owner['current_guard']['receipt'], 'wrong retained normal 168 owner')
        return row
    return None


def advancing_state(older, newer):
    if not older:
        return
    need(newer and older['intent'] == newer['intent'] and older['prior_trace_terminal'] == newer['prior_trace_terminal']
         and STAGES.index(newer['stage']) >= STAGES.index(older['stage']), 'normal 168 changed generations or lost protection')
    for key in ('actor', 'admission', 'first_worker', 'observer_row'):
        if older.get(key) is not None:
            need(older[key] == newer.get(key), 'changed normal 168 ' + key)


def freeze(c):
    live = status168.inspect()
    oldref = c.fleet.get(FIELD)
    if oldref:
        advancing_state(checked(oldref)['state'], live)
    path = c.paths['out'] / 'METERED168_OBSERVATION.json'
    if not path.exists():
        # A completed predecessor generated by the older package has no normal
        # capture. Keep its historical result and select new work on the next sample.
        if (c.paths['out']/'ROOT_COMPLETE_OPERATIONAL_FLEET.json').exists():
            need(not oldref and not any(r['range']=='168' for r in c.cfg['replays']),
                 'missing scheduled normal 168 capture')
            return None
        if live:
            need(c.retired168 and live['prior_trace_terminal'] == c.fleet['terminal168_trace_mismatch'],
                 'normal 168 crossed its original private trace')
        ensure_dir(c.paths['out'])
        durable(path, dict(schema='horizon-normal168-scheduled-capture-v1', fleet=c.fleet_ref,
                           sample=c.sample_ref, state=live))
    reference = bound(path)
    value = checked(reference)
    need(value['schema'] == 'horizon-normal168-scheduled-capture-v1' and value['sample'] == c.sample_ref
         and value['fleet'] == c.fleet_ref, 'normal 168 from another sample')
    advancing_state(value['state'], live)
    if not value['state']:
        return None
    return dict(reference=reference,state=value['state'])

def interpret(c, observed_lane):
    capture = c.metered168
    c.metered168_row = None
    configs = [r for r in c.cfg['replays'] if r['range'] == '168']
    samples = [r for r in c.sample['replays'] if r['range'] == '168']
    need(len(configs) == len(samples) <= 1, 'different normal 168 sample count')
    if not capture or not capture['state']['ordinary_canonical']:
        need(not configs, '168 sampled before guarded admission')
        return
    state = capture['state']
    actor = state['actor']
    config = state['observer_row']
    ad = checked(state['admission'])
    old = previous(c.fleet)
    progress = last = None
    measured = False
    if configs:
        need(configs == [config], 'foreign normal 168 scheduled identity')
        sample, = samples
        first = checked(state['first_worker'])
        measured = observed_lane(sample, config, actor['producer_invocation_id'], actor['producer_pid'])
        for edge in ('worker_before','worker_after'):
            worker = sample[edge]
            need(worker['pid'] == first['worker_pid'] and worker['matching_workers'] == 1
                 and worker['executable_beneath_bound_scratch'], 'different sampled 168 worker')
        progress = sample['useful_work']
        last = progress.get('last')
        if measured:
            need(FIRST <= progress['first']['slot'] <= last['slot'] <= LAST and last['terminal_slot'] == LAST,
                 'normal 168 progress outside epoch')
            prior = (old or {}).get('last_progress')
            measured = progress['counter_resets'] == 0 and (not prior or (
                last['realtime_microseconds'] > prior['realtime_microseconds'] and last['slot'] >= prior['slot']
                and last['transactions'] >= prior['transactions']))
        c.lanes[168] = sample
        c.advancing[168] = measured
    stage = 'worker' if config else 'bootstrap'
    phase = 'replay' if measured or (old and old['phase'] == 'replay') else 'verification'
    unit = dict(Id=status168.U, InvocationID=actor['producer_invocation_id'], MainPID=str(actor['producer_pid']))
    row = dict(epoch=168, unit=unit, start_ticks=actor['start_ticks'], stage=stage, capture=capture['reference'],
               phase=phase, admission=state['admission'],
               first_guard=ad['first_guard'], post_guard_capacity=ad['post_guard_capacity'],
               first_worker=state['first_worker'], guard_protection=state['current_guard']['receipt'],
               guard_timer=state['current_guard']['timer'], observer=c.sample_ref, observer_config=config,
               in_current_observer=bool(configs), scratch_path=config['scratch_path'] if config else None,
               measured_progress=measured, progress=progress,
               last_progress=last if measured else (old or {}).get('last_progress'))
    c.metered168_row = row
    keep = [r for r in c.next_cfg['replays'] if r['range'] != '168']
    if config:
        keep.append(deepcopy(config))
    c.next_cfg['replays'] = sorted(keep, key=lambda r:int(r['range']))


def bootstrap(c):
    return int(c.metered168_row is not None and c.metered168_row['stage'] == 'bootstrap')


def install(c, f):
    if not c.metered168:
        return
    f[FIELD] = c.metered168['reference']
    r = c.metered168_row
    if not r:
        return
    boot = bootstrap(c)
    f['actual_active_bootstraps' if boot else 'actual_executing_replays'].append(r)
    for k, n in (('canonical_producer_count',1),('active_producer_count',1),('bootstrap_count',boot),
                 ('guarded_bootstrap_owner_count',boot),('live_replay_count',1-boot)):
        f[k] = f.get(k,0) + n
    e = next(e for e in f['epochs'] if e['epoch'] == 168)
    e.pop('current_bootstrap',None)
    e.pop('current_replay',None)
    e['current_bootstrap' if boot else 'current_replay'] = r
    e.update(current_repair_owner=None,no_live_producer_claimed=False,repair_open=False,
             state='bootstrap' if boot else 'executing',current_status_scope='Normal metered epoch 168 under its admitted guard.')


def forecast(c, old, archive):
    import delivery_eta
    row = c.metered168_row
    age = round((c.now - utc(old['sampled_at_utc'])).total_seconds()*1000)
    size = archive['size'] if archive else old['jet_size_bytes'] if previous(c.fleet) else 0
    need(age >= 0 and size >= 0, 'invalid normal 168 clock or size')
    # Keep the current authenticated forecast until a normal worker supplies its own rate.
    remain = old['estimated_remaining_millis'] - age
    if row['measured_progress']:
        work = row['progress']
        if work['elapsed_seconds'] >= 60:
            need(work['slot_delta'] > 0 and LAST > work['last']['slot'], 'normal 168 requires terminal reconciliation')
            quote = delivery_eta.prepare(c,168,size)
            remain = round((LAST-work['last']['slot'])*work['elapsed_seconds']/work['slot_delta']*1100)+quote['total_millis']
    need(remain > 0, 'normal 168 forecast expired')
    return dict(old, phase=row['phase'], jet_size_bytes=size, sampled_at_utc=c.stamp,
                elapsed_execution_millis=old['elapsed_execution_millis']+age, estimated_remaining_millis=remain), archive
